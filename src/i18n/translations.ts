export type TranslationKey = keyof typeof translations.en;

export function getTranslation(lang: Language, key: TranslationKey): string {
  return translations[lang]?.[key] || translations.en[key] || '';
}

export function getSpiceLabel(lang: Language, level: string): string {
  if (level === 'extra_hot') return translations[lang]?.extraHot || 'Extra Hot';
  if (level === 'hot') return translations[lang]?.hot || 'Hot';
  if (level === 'medium') return translations[lang]?.medium || 'Medium';
  return translations[lang]?.mild || 'Mild';
}
